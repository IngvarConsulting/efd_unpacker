"""
Версия платформы из установщика Windows.

У дистрибутивов под Linux и macOS версия лежит в имени файла —
`setup-full-8.3.27.2342-x86_64.run`, — и опознание читает её оттуда. У
установщика Windows в именах записей версии нет вовсе: внутри `Data1.cab`,
`setup.exe`, `1CEnterprise 8 Thin client (x86-64).msi` и четыре десятка
`.mst` с языковыми ресурсами. Имя msi честно даёт компоненту и архитектуру,
но не номер выпуска.

`Setup.ini`, на который можно было рассчитывать, в архиве отсутствует:
файлы `0x0409.ini` и им подобные — это строки InstallShield, а не настройки.

Зато сам номер в msi есть — строкой в пуле, рядом с именами каталогов:
установщик кладёт платформу в подкаталог с номером версии. Оттуда и берём.

Полноценный разбор MSI (OLE2, таблицы, пул строк) ради одной строки не
окупается: файл на три мегабайта, а нужно из него четыре числа.
"""

from __future__ import annotations

import re
from typing import Optional

#: Где в msi лежит версия платформы.
#:
#: Просто «четыре числа через точку» не годится: в полном дистрибутиве таких
#: двадцать пять, и три из них начинаются с восьмёрки — 8.0.275.1 и 8.9.10.0
#: принадлежат встроенной JRE. Выбирать из них было бы гаданием.
#:
#: Поэтому берём номер, стоящий вплотную к известному маркеру. Маркеров два,
#: и они дополняют друг друга: DesktopFolder есть у тонкого клиента и у
#: полного 64-битного, ShortcutFolderVersion — у всех вариантов windows*.
#: Вместе они покрывают все десять проверенных архивов (8.3.27.2342 и
#: 8.5.4.1683, тонкий клиент, сервер, полный, 32 и 64 бита), а там, где
#: срабатывают оба, дают одно и то же.
#:
#: Границы у номера обязательны. Без них шаблон съедает цифры, идущие
#: следом: в пуле строк значения лежат вплотную, без разделителей.
#: Мажорная часть ограничена двумя цифрами. Без ограничения `\d+` в начале
#: безгранична, и «8315112348.5.4.1683» — формально те же четыре части: перед
#: номером в пуле идут значения вплотную, и шаблон прихватывал их цифры.
#: У платформы мажорная версия однозначная (8), запас — на случай девятки и
#: дальше.
VERSION = re.compile(
    rb"DesktopFolder(\d{1,2}\.\d+\.\d+\.\d+)(?![\d.])"
    rb"|(?<![\d.])(\d{1,2}\.\d+\.\d+\.\d+)ShortcutFolderVersion"
)

#: Сколько байт читаем. Msi тонкого клиента — три мегабайта; предел с запасом
#: и нужен ровно затем, чтобы подставной или повреждённый файл не уехал в
#: память целиком.
SIZE_LIMIT = 64 * 1024 * 1024

#: Кусок чтения. Номер версии короткий, и чтобы он не разорвался по границе
#: кусков, соседние читаются с нахлёстом.
CHUNK = 1024 * 1024
OVERLAP = 64


def read_version(path: str) -> str:
    """Версия платформы из msi на диске. Пустая строка, если не узнали."""
    try:
        with open(path, "rb") as handle:
            return version_from_stream(handle)
    except Exception:  # noqa: BLE001 - опознание не должно падать из-за версии
        return ""


def version_from_stream(handle) -> str:
    """
    Версия платформы из потока. Пустая строка, если её нет или она не одна.

    Потоком, а не путём: лист контейнера открывается именно так, и читать
    версию тем же способом, что и оглавление .efd, дешевле, чем заводить свой.

    Не одна — значит не узнали: две разные версии в одном установщике мы
    объяснить не можем, и выбрать из них наугад хуже, чем не показать
    ничего. По тому же правилу пустой ответ даёт и нечитаемый файл:
    опознание вида от этого не страдает, оно идёт по именам записей.
    """
    found = set()
    try:
        tail = b""
        read = 0
        while read < SIZE_LIMIT:
            chunk = handle.read(CHUNK)
            if not chunk:
                break
            read += len(chunk)
            for groups in VERSION.findall(tail + chunk):
                found.update(group for group in groups if group)
            if len(found) > 1:
                return ""
            tail = chunk[-OVERLAP:]
    except Exception:  # noqa: BLE001 - опознание не должно падать из-за версии
        return ""
    return found.pop().decode("ascii") if len(found) == 1 else ""


def version_of(path: Optional[str]) -> str:
    """Удобная обёртка: путь может быть и не найден."""
    return read_version(path) if path else ""
